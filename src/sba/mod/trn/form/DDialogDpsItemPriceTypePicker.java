    public void resetForm() {
        mnFormResult = DLibConsts.UNDEFINED;
        mbFirstActivation = true;
        
        moRadItemPriceTypeBizPartner.setSelected(true);
        jlstItemPriceTypes.clearSelection();
    }
    
    @Override
    public void addAllListeners() {
        moRadItemPriceTypeBizPartner.addItemListener(this);
        moRadItemPriceTypeCustom.addItemListener(this);
    }

