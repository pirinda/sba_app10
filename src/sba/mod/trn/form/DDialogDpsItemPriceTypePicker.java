    private void selectItemPriceType(int itemPriceType) {
        int index = -1;
        
        for (int element = 0; element < jlstItemPriceTypes.getModel().getSize(); element++) {
            if (((DGuiItem) jlstItemPriceTypes.getModel().getElementAt(element)).getPrimaryKey()[0] == itemPriceType) {
                index = element;
                break;
            }
        }

        if (index == -1) {
            jlstItemPriceTypes.clearSelection();
        }
        else {
            jlstItemPriceTypes.setSelectedIndex(index);
        }
    }
    
    private void setBizPartnerItemPriceType(int itemPriceType) {
        mnBizPartnerItemPriceType = itemPriceType;
        
        jtfItemPriceTypeBizPartner.setText((String) miClient.getSession().readField(DModConsts.MS_ITM_PRC_TP, new int[] { mnBizPartnerItemPriceType }, DDbRegistry.FIELD_NAME));
        jtfItemPriceTypeBizPartner.setCaretPosition(0);
    }
    
    private void setEffectiveItemPriceType(int itemPriceType) {
        if (itemPriceType == mnBizPartnerItemPriceType) {
            if (!moRadItemPriceTypeBizPartner.isSelected()) {
                moRadItemPriceTypeBizPartner.setSelected(true); // it will trigger item event
            }
        }
        else {
            if (!moRadItemPriceTypeCustom.isSelected()) {
                moRadItemPriceTypeCustom.setSelected(true); // it will trigger item event
            }
            
            selectItemPriceType(itemPriceType);
        }
    }
    
    private int getItemPriceType() {
        int itemPriceType = DLibConsts.UNDEFINED;
        
        if (moRadItemPriceTypeCustom.isSelected()) {
            if (jlstItemPriceTypes.getSelectedIndex() >= 0) {
                itemPriceType = ((DGuiItem) jlstItemPriceTypes.getModel().getElementAt(jlstItemPriceTypes.getSelectedIndex())).getPrimaryKey()[0];
            }
        }
        
        return itemPriceType;
    }
    
    private void itemStateChangedItemPriceType() {
        if (moRadItemPriceTypeBizPartner.isSelected()) {
            jlstItemPriceTypes.setEnabled(false);
            
            jlstItemPriceTypes.clearSelection();
        }
        else {
            jlstItemPriceTypes.setEnabled(true);
            
            selectItemPriceType(mnBizPartnerItemPriceType);
        }
    }

