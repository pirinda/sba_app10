    @Override
    public DGuiValidation validateForm() {
        DGuiValidation validation = moFields.validateFields();
        
        if (moRadItemPriceTypeCustom.isSelected()) {
            if (jlstItemPriceTypes.getSelectedIndex() < 0) {
                validation.setMessage(DGuiConsts.ERR_MSG_FIELD_REQ + "'" + DGuiUtils.getLabelName(jlItemPriceTypes) + "'.");
                validation.setComponent(jlstItemPriceTypes);
            }
        }

        return validation;
    }

    @Override
    public void setValue(final int type, final Object value) {
        switch (type) {
            case PARAM_BPR_ITM_PRC_TP:
                setBizPartnerItemPriceType((int) value);
                break;
            case PARAM_EFF_ITM_PRC_TP:
                setEffectiveItemPriceType((int) value);
                break;
            default:
                miClient.showMsgBoxError(DLibConsts.ERR_MSG_OPTION_UNKNOWN);
        }
    }

    @Override
    public Object getValue(final int type) {
        Object value = null;

        switch (type) {
            case DModConsts.MS_ITM_PRC_TP:
                value = getItemPriceType();
                break;
            default:
                miClient.showMsgBoxError(DLibConsts.ERR_MSG_OPTION_UNKNOWN);
        }

        return value;
    }

    @Override
    public void itemStateChanged(ItemEvent e) {
        if (e.getSource() instanceof DBeanFieldRadio && e.getStateChange() == ItemEvent.SELECTED) {
            DBeanFieldRadio field = (DBeanFieldRadio) e.getSource();
            if (field == moRadItemPriceTypeBizPartner || field == moRadItemPriceTypeCustom) {
                itemStateChangedItemPriceType();
            }
        }
    }
